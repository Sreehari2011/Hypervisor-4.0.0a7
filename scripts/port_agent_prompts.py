def _extract(source: str, name: str) -> str:
    m = re.search(
        rf"^{re.escape(name)} = \((.*?)^\)", source, re.M | re.S)
    if not m:
        raise SystemExit(f"constant {name} not found in oracle source")
    return f"{name} = ({m.group(1)})\n"


def main() -> int:
    import os
    if TARGET.exists() and "UX-02" in TARGET.read_text(
            encoding="utf-8")[:2000] \
            and "--force-verbatim" not in sys.argv:
        print("target carries the UX-02 AEGIS adaptation; refusing to "
              "overwrite with oracle-verbatim texts. Pass --force-verbatim "
              "to revert to the 3.7.3 originals (then re-apply UX-02 or "
              "re-cut the sha pins in tests/test_agents.py).",
              file=sys.stderr)
        return 1
    oracle_tree = Path(os.environ.get("AEGIS_ORACLE_TREE")
                       or ORACLE_DEFAULT)
    src = oracle_tree / "src" / "core" / "subagent_prompts.py"
    if not src.exists():
        print(f"oracle source missing: {src}", file=sys.stderr)
        return 1
    source = src.read_text(encoding="utf-8")
    parts = [HEADER]
    for c in CONSTANTS:
        parts.append(_extract(source, c))
        parts.append("\n\n")
    body = "".join(parts).rstrip() + "\n"
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(body, encoding="utf-8")
    print(f"wrote {TARGET} ({len(body)} bytes)")

    # byte-identity assertion against the live oracle when present
    ns: dict = {}
    exec(body, ns)                       # noqa: S102 - generated locally
    ons: dict = {}
    oracle_ns_src = re.sub(
        r"^GENERATED FILE.*?\"\"\"", '"""oracle prompts"""',
        source, count=1, flags=re.S)
    exec(oracle_ns_src, ons)             # noqa: S102
    for c in CONSTANTS:
        if ns[c] != ons[c]:
            print(f"BYTE MISMATCH on {c}", file=sys.stderr)
            return 1
    print("byte-identity: 6/6 constants verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
